"""Convert the generated creation-tale plates into font-calibrated ASCII.

Run from either the Sites checkout or the published GitHub layout.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from portrait_to_ascii import read_image, convert, render, FONT

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT/'dist' if (ROOT/'dist/index.html').exists() else ROOT
ART = ROOT/'art/fable'
frames = {}
plates = []
for path in sorted(ART.glob('*-source.png')):
    key = path.stem.removesuffix('-source')
    lines = convert(read_image(path), columns=112, cell_aspect=.6,
                    gamma=.83, black=.045, ramp=' .:-=+coOX#@')
    frames[key] = lines
    (ART/(key+'.txt')).write_text('\n'.join(lines)+'\n', encoding='ascii')
    plate = render(lines, size=10, padding=12)
    plate.save(ART/(key+'-ascii.png'))
    plates.append((key,plate))
assert len(frames)==4, 'All four generated plates are required.'
(WEB/'js/fable-art.js').write_text('// Generated by scripts/build-fable.py. Printable ASCII only.\nexport const FABLE_ART='+json.dumps(frames,separators=(',',':'))+';\n')
w = max(im.width for _,im in plates)
h = max(im.height for _,im in plates)+28
sheet=Image.new('RGB',(w*2,h*2),'black')
draw=ImageDraw.Draw(sheet)
font=ImageFont.truetype(str(FONT),16)
for i,(name,plate) in enumerate(plates):
    x,y=(i%2)*w,(i//2)*h
    draw.text((x+12,y+6),name[3:].replace('-',' ').upper(),font=font,fill='#aaa')
    sheet.paste(plate,(x,y+28))
sheet.save(ROOT/'docs/somnia-fable-ascii.png')
print('Four ASCII plates: '+', '.join(f'{k}: {len(v[0])}x{len(v)}' for k,v in frames.items()))
