"""Turn the generated four-building sheet into small, playable ASCII stamps.

Keep a literal density conversion for comparison. At map scale, sample the roof
silhouette, simplify interior texture, and use explicit window/door/sign glyphs.
Collision and service metadata stay independent from raster brightness.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from portrait_to_ascii import read_image, convert, render, FONT

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT/'dist' if (ROOT/'dist/index.html').exists() else ROOT
ART = ROOT/'art/buildings'
source = read_image(ART/'bracken-source.png')
specs = [
    ('harbor_inn', 0, 0, 23, 11, 7, 'DRY NET', 'inn', 'The Dry Net'),
    ('harbor_shop', 1, 0, 21, 10, 6, 'SUPPLIES', 'shop', 'Supply counter'),
    ('harbor_cottage', 0, 1, 13, 7, 4, '', None, None),
    ('harbor_ward', 1, 1, 21, 10, 6, 'SLEEP WARD', 'clinic', 'Sleep ward'),
]
stamps = {}
plates = []
for name, cx, cy, width, height, roof_rows, sign, service, label in specs:
    tw, th = source.width//2, source.height//2
    crop = source.crop((cx*tw,cy*th,(cx+1)*tw,(cy+1)*th))
    crop = crop.crop(crop.point(lambda v:255 if v>50 else 0).getbbox())
    scaled = crop.resize((width*30,height*50),Image.Resampling.LANCZOS)
    raw = convert(scaled,width,.6,1,.12,style='contour')
    (ART/(name+'-raw.txt')).write_text('\n'.join(raw)+'\n')
    small = crop.resize((width,height),Image.Resampling.BOX)
    art = []
    for y in range(roof_rows):
        occupied = [x for x in range(width) if small.getpixel((x,y))>=45]
        row = [' ']*width
        # Keep separate chimney/turret shapes at the top, merge fine roof grain.
        runs=[]
        for x in occupied:
            if runs and x-runs[-1][-1]<= (3 if y>=2 else 1):runs[-1].append(x)
            else:runs.append([x])
        for run in runs:
            a,b=run[0],run[-1]
            for x in range(a,b+1):row[x]='='
            if a==b:row[a]='+'
            else:row[a],row[b]='/', '\\'
        if name=='harbor_shop' and y==roof_rows-1:
            # The mockup's striped awning, expressed as regular ASCII cloth.
            row=list('/'+''.join('#' if x%4<2 else '=' for x in range(width-2))+'\\')
        art.append(''.join(row))
    # Readable structural features from the mockup, snapped to character cells.
    # Tiny window panes and roof beams cannot survive density sampling at 23x11.
    def detail(y,x,text):
        row=list(art[y]);row[x:x+len(text)]=text;art[y]=''.join(row)
    if name=='harbor_inn':
        detail(0,3,'___');detail(1,3,'|#|');detail(2,3,'|#|')
        for y,text in [(1,' /\\ '),(2,' /[]\\ '),(3,' /|  |\\ '),(4,'/__|__|__\\')]:
            detail(y,13-len(text)//2,text)
    elif name=='harbor_cottage':
        detail(0,2,'_ ');detail(1,2,'H')
    elif name=='harbor_ward':
        detail(2,8,'| o |')
    door=width//2
    def facade(fill=' '):return list(' |'+fill*(width-4)+'| ')
    if sign:
        row=facade();start=(width-len(sign))//2
        row[start:start+len(sign)]=sign;art.append(''.join(row))
    row=facade()
    for x in (3,width-5):row[x:x+2]=list('[]')
    row[door]='|';art.append(''.join(row))
    row=facade();row[door-1:door+2]=list('| |');art.append(''.join(row))
    row=facade('_');row[door]='+';art.append(''.join(row))
    assert len(art)==height and all(len(row)==width for row in art)
    stamp={'art':art,'doors':[[door,height-1]],'source':'art/buildings/bracken-source.png'}
    if service:stamp['service']=[door,height-1,service,label]
    stamps[name]=stamp
    (ART/(name+'.txt')).write_text('\n'.join(art)+'\n')
    plate=render(art,size=24);plate.save(ART/(name+'-ascii.png'));plates.append((name,plate))
(WEB/'js/building-art.js').write_text('// Generated by scripts/build-buildings.py. ASCII art plus explicit gameplay metadata.\nexport const HARBOR_STAMPS='+json.dumps(stamps,separators=(',',':'))+';\n')
sheet=Image.new('RGB',(800,680),'black');d=ImageDraw.Draw(sheet)
font=ImageFont.truetype(str(FONT),18)
for i,(name,plate) in enumerate(plates):
    x,y=(i%2)*400,(i//2)*340
    d.text((x+18,y+10),name.replace('harbor_','').upper(),font=font,fill='white')
    sheet.paste(plate,(x,y+36))
sheet.save(ROOT/'docs/bracken-building-ascii.png')
print('Built four image-derived harbor stamps with working doors.')
