#!/usr/bin/env python3
"""Convert generated poses to stable ASCII frames. Requires Pillow.

Only the mouth rectangle is taken from each converted speaking pose; all other
characters come from the original, preventing tiny generative differences from
making hair, eyes, or clothing flicker. No raster images are used in the game.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from portrait_to_ascii import read_image, pixel_portrait, convert, render, FONT

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / 'dist' if (ROOT / 'dist/index.html').exists() else ROOT
SOURCE = ROOT / 'art/portraits/mara'
POSES = ['closed', 'parted', 'open', 'round']
MOUTH = [26, 21, 42, 27]  # x0, y0, x1, y1 in the 64 x 38 text grid
frames = {}
pixels = {}
for pose in POSES:
    pixels[pose] = pixel_portrait(read_image(SOURCE / f'{pose}-generated.png'))
    pixels[pose].save(SOURCE / f'{pose}-64.png')
    lines = convert(pixels[pose], columns=64, font_path=FONT)
    if pose != 'closed':
        x0, y0, x1, y1 = MOUTH
        lines = [base[:x0] + lines[y][x0:x1] + base[x1:] if y0 <= y < y1 else base
                 for y, base in enumerate(frames['closed'])]
    frames[pose] = lines
    (SOURCE / f'{pose}.txt').write_text('\n'.join(lines) + '\n', encoding='ascii')

asset = {'columns': 64, 'rows': 38, 'mouthBounds': MOUTH, 'frames': frames}
(WEB / 'js/portraits.js').write_text(
    '// Generated by scripts/build-mara-portraits.py. Printable ASCII only.\n'
    + 'export const MARA = ' + json.dumps(asset, indent=2) + ';\n', encoding='ascii')

# A reproducible contact sheet for reviewing generation and conversion together.
font = ImageFont.truetype(str(FONT), 20)
plate = Image.new('RGB', (1152, 640), 'black')
draw = ImageDraw.Draw(plate)
for i, pose in enumerate(POSES):
    left = i * 288 + 16
    draw.text((left, 18), pose.upper(), font=font, fill='#eeeeea')
    plate.paste(pixels[pose].resize((256, 256), Image.Resampling.NEAREST), (left, 52))
    art = render(frames[pose], size=6, padding=0)
    plate.paste(art, (left + (256-art.width)//2, 336))
plate.save(ROOT / 'docs/mara-mouth-poses.png')
print('Built four 64 x 38 ASCII frames; only the 16 x 6 mouth region changes.')
